"""INTERACT-004: actual paragraph → pinned native IDs → trained causal relation.

VL-I runs lightweight tokenizer and trusted range navigation. Original Qwen
or DeepSeek checkpoint weights stay remotely resident. The output is a partial
trained numerical construction, NOT a full paragraph generated by the model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from vli.large_model_comparison import SOURCES
from vli.operative_model import ground as trained_ground, _qwen
from vli.pinned_text_ground import (
    TOKENIZER_SOURCES,MAX_ASSET_BYTES,admit,text_intention,tokenize,
    validate_observation)
from vli.qwen_causal_head import QwenCausalHead
from vli.token_embedding_ground import (
    token_intention,observe_token_row,TokenEmbeddingSession)


DEFAULT_TEXT="Communication can support computation when information is interpreted through a virtual layer."


def run(route, *, text=DEFAULT_TEXT, steps=2):
    from experiments.model_fabric.scaled_model_fabric import (
        QualifiedShardNavigator,MAX_INDEX_BYTES)
    from experiments.model_fabric.scaled_model_lab import (
        _url,_fetch_metadata,pinned_hf_range_host)
    if route not in SOURCES or type(steps) is not int or not 1<=steps<=8:
        raise ValueError("Only original-scale pinned models and bounded steps admitted")
    source=SOURCES[route]
    index=_fetch_metadata(_url(source["model"],source["revision"],
                             "model.safetensors.index.json"),MAX_INDEX_BYTES)
    nav=QualifiedShardNavigator(
        model=source["model"],revision=source["revision"],
        index_raw=index,range_host=pinned_hf_range_host(
            source["model"],source["revision"]),
        approved_hosts={"pinned-huggingface-https-range"})
    g=trained_ground(route,nav.index)
    tok_src=TOKENIZER_SOURCES[route]
    tok_raw=_fetch_metadata(_url(tok_src["repository"],tok_src["revision"],
                                 tok_src["filename"]),MAX_ASSET_BYTES)
    tg,runtime=admit(g,tok_raw)
    intent=text_intention(tg,text)
    ids=tokenize(tg,runtime,intent)
    validate_observation(g,tg,intent,ids)
    count=min(steps,ids["token_count"])
    if count < 2:
        raise ValueError("Tokenized paragraph has fewer than two native vocabulary IDs")
    outputs=[]
    if route=="qwen-27b":
        causal=QwenCausalHead(g,head=0)
        for token_id in ids["token_ids"][:count]:
            row_id=token_intention(g,token_id)
            vector,witness=observe_token_row(nav,g,row_id)
            # A separate original-weight 48-gate pass is a cross-adapter
            # check on the same actual token input.
            gate_result=_qwen(nav,None,hidden=vector)
            transition=causal.next(nav,vector,witness,expected_head=causal.chain)
            if abs(transition["head_beta"]-gate_result["beta"][0])>1e-10:
                raise ValueError("Qwen causal head gate and full 48-gate projection disagree")
            outputs.append({
                "token_id":token_id,
                "embedding_sha256":witness["embedding_sha256"],
                "embedding_bytes":witness["embedding_bytes"],
                "trained_gate_mean_beta":gate_result["mean_beta"],
                "trained_gates_above_half":sum(x>.5 for x in gate_result["beta"]),
                "selected_causal_head_output":transition[
                    "output_row0_selected_head_contribution"],
                "head_beta":transition["head_beta"],
                "causal_recurrent_digest":transition["causal_recurrent_state_digest"],
                "causal_convolution_digest":transition[
                    "causal_convolution_history_digest"],
                "independent_recurrence_max_abs_error":transition[
                    "independent_recurrence_max_abs_error"],
                "qualified_range_count":transition["new_weight_ranges"],
                "range_chain":transition["range_chain"],
                "scope":transition["scope"],
            })
        cp=causal.checkpoint()
        recovered=QwenCausalHead.restore(g,cp,
                             expected_checkpoint_digest=cp["checkpoint_digest"])
        assert recovered.chain==causal.chain and recovered.position==count
        causal_state={
            "type":"qwen_original_layer0_selected_head_recurrent",
            "head_id":0,
            "tokens_processed":count,
            "checkpoint_head":cp["checkpoint_digest"],
            "recovery_verified":True,
            "full_layer_completed":False,
        }
        status="REAL_PINNED_TEXT_TO_QWEN_CAUSAL_SELECTED_HEAD"
    else:
        s=TokenEmbeddingSession(g,observer="vli-pinned-text")
        for token_id in ids["token_ids"][:count]:
            item=s.operate(nav,token_intention(g,token_id),
                           expected_head=s.head,render=False)
            output=item["trained"]
            outputs.append({
                "token_id":token_id,
                "embedding_sha256":output["embedding_witness"]["embedding_sha256"],
                "embedding_bytes":output["embedding_witness"]["embedding_bytes"],
                "selected_experts":item["constructed"]["selected"],
                "weighted_partial_contribution":item["constructed"]["weighted_partial"],
                "qualified_range_count":output["new_ranges"],
                "range_chain":output["range_chain_head"],
                "scope":"related_Flash_tokenizer_and_embedding_fed_router_probe_not_true_post_attention_state",
            })
        cp=s.checkpoint()
        restored=TokenEmbeddingSession.restore(
            g,cp,expected_head=cp["checkpoint_digest"])
        causal_state={"type":"deepseek_embedding_fed_router_probe",
                      "tokens_processed":count,
                      "checkpoint_head":cp["checkpoint_digest"],
                      "recovery_verified":restored.head==s.head,
                      "full_layer_completed":False}
        status="RELATED_TOKENIZER_TEXT_TO_DEEPSEEK_PARTIAL_ROUTER_PROBE"
    if len({x["embedding_sha256"] for x in outputs})!=len(outputs):
        raise ValueError("Distinct original text token rows are not distinguishable")
    return {
        "schema":"vl-i.pinned-text-causal-construction-lab.v1",
        "status":status,"route":route,
        "model":source["model"],"model_revision":source["revision"],
        "model_original_advertised_bytes":source["advertised_bytes"],
        "model_index_sha256":source["index_sha256"],
        "tokenizer_asset_source":tok_src["repository"],
        "tokenizer_asset_revision":tok_src["revision"],
        "tokenizer_sha256":tg["asset_sha256"],
        "tokenizer_source_grade":tg["source_grade"],
        "tokenizer_ground_digest":tg["ground_digest"],
        "paragraph_text_sha256":ids["text_sha256"],
        "native_token_ids":ids["token_ids"],
        "native_token_count":ids["token_count"],
        "native_token_offsets":ids["token_offsets"],
        "tokenizer_roundtrip_exact":True,
        "real_trained_token_steps":outputs,
        "causal_state":causal_state,
        "weight_bytes_persisted_in_virtual_ground":0,
        "full_model_language_inference_completed":False,
        "decoded_full_vocab_logits":False,
        "scope":"literal_paragraph_to_original_vocabulary_IDs_to_real_trained_partial_math",
    }


def main(argv=None):
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model",choices=tuple(SOURCES),required=True)
    ap.add_argument("--text",default=DEFAULT_TEXT)
    ap.add_argument("--steps",type=int,default=2)
    ap.add_argument("--out",required=True)
    a=ap.parse_args(argv)
    dest=Path(a.out);dest.parent.mkdir(parents=True,exist_ok=True)
    try:
        out=run(a.model,text=a.text,steps=a.steps)
    except (ValueError,OSError,TimeoutError,RuntimeError,ImportError,OverflowError) as e:
        out={"schema":"vl-i.pinned-text-causal-construction-lab.v1",
             "status":"UNRESOLVED","model":a.model,
             "error_type":type(e).__name__,
             "no_claim_of_numerical_completion":True}
    dest.write_text(json.dumps(out,sort_keys=True,indent=2,
                     allow_nan=False)+"\n",encoding="utf-8")
    print("PINNED_TEXT_CAUSAL_GROUND",out["status"],a.model)
    return 0 if out["status"].startswith(("REAL_","RELATED_")) else 2


if __name__=="__main__":
    raise SystemExit(main())
